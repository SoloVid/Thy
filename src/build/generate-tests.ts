import { readFile, writeFile } from "node:fs/promises"
import { join } from "node:path"
import { rootDir } from "root-dir"
import { runNodeCli } from "utils/run-node-cli"
import { walkFiles } from "utils/walk-files"
import { profileSection } from "website/build/time"

runNodeCli(async () => {
  const inputDir = join(rootDir, "src/test/programs")
  await walkFiles(
    {
      rootDir: inputDir,
    },
    async (relativePath) => {
      if (!relativePath.endsWith("/input/main.thy")) {
        return
      }
      const dir = relativePath.replace(/\/input\/main\.thy$/, "")
      await profileSection(`Generate ${dir}/generated.test.ts`, async () => {
        const expectedValue = await readFile(
          join(inputDir, dir, "expected.json"),
          "utf-8",
        )

        await writeFile(
          join(inputDir, dir, "generated.test.ts"),
          `// DO NOT MODIFY BY HAND
// This file was generated by src/build/generate-tests.ts

import { join } from "node:path"
import { test } from "test-framework"
import { verifyInterpreterAndCompiler } from "test/verify"
import logic from "./output/main.thy"

test("${dir} verify", async () => {
  await verifyInterpreterAndCompiler({
    inputDir: join(__dirname, "input"),
    logic: logic,
    outputDir: join(__dirname, "output"),
    expectedValue: ${expectedValue},
  })
})
`,
        )
      })
    },
  )
})
